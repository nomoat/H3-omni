"""Translate the upstream scalar Metal primitives into reviewable CUDA source.

Matrix multiplication, attention, allocation and convolutions are implemented
separately. This intentionally excludes Metal TensorOps and int8 fast paths.
Run from any directory; generated files remain checked in for ordinary builds.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
shader = (ROOT / "h3_shaders.metal").read_text()
host = (ROOT / "h3_gpu.m").read_text()


def blocks(text, pattern):
    for m in re.finditer(pattern, text):
        start = text.index("{", m.end())
        depth, end = 1, start + 1
        while depth:
            depth += (text[end] == "{") - (text[end] == "}")
            end += 1
        yield m, text[m.start():start], text[start:end]


names = """silu_f32 cast_f32_to_bf16 cast_bf16_to_f32 rms_norm_f32
scale_add_f32 layer_norm_f32 video_qkv_rope_f32 adaln_f32 gate_f32
qkv_rope_f32 swiglu_f32 vae_encoder_pad_f32 vae_encoder_group_norm_silu_f32
weight_norm_f32 add_scaled_f32 alias_free_snake_f32 snake1d_f32
audio_qkv_split_f32 audio_attention_pool_f32 geglu_f32 clip_f32
silu_bf16 rms_norm_bf16 layer_norm_bf16 gelu_bf16 vision_qkv_rope_bf16
adaln_bf16 gate_bf16 qkv_rope_bf16 swiglu_bf16 embedding_bf16
text_qk_rope_bf16 head_rms_norm_bf16 rope_text_bf16 add_bf16 sub_bf16
euler_bf16 silu_mul_bf16""".split()
selected = {"h3_" + n for n in names}


def translate(s):
    s = re.sub(r"\bdevice\s+", "", s)
    s = re.sub(r"\bthreadgroup\s+", "__shared__ ", s)
    s = s.replace("threadgroup_barrier(mem_flags::mem_threadgroup)", "__syncthreads()")
    s = re.sub(r"\bfma\(", "fmaf(", s)
    s = re.sub(r"\bexp\(", "expf(", s)
    s = re.sub(r"\btanh\(", "tanhf(", s)
    s = re.sub(r"\bsin\(", "sinf(", s)
    s = re.sub(r"\bcos\(", "cosf(", s)
    s = re.sub(r"\bsqrt\(", "sqrtf(", s)
    s = re.sub(r"\brsqrt\(", "rsqrtf(", s)
    s = s.replace("M_PI_F", "3.14159265358979323846f")
    return s


structs = "\n".join(m.group(0) for m in re.finditer(r"struct \w+\s*\{[^}]*\};", shader))
out = ["// Generated by cuda/translate_primitives.py; source: h3_shaders.metal.\n", structs]
out += ["""
__device__ inline float h3_bf16_to_f32(ushort x) { return __uint_as_float(uint(x) << 16); }
__device__ inline ushort h3_f32_to_bf16(float x) {
    return __bfloat16_as_ushort(__float2bfloat16_rn(x));
}
template<class T> __device__ T clamp(T x, T a, T b) { return min(max(x,a),b); }
__device__ inline float bf16_round(float x) {
    return h3_bf16_to_f32(h3_f32_to_bf16(x));
}
// Match PyTorch 2.9.1 vectorized RMSNorm's 128-thread, four-value reduction.
// The launch can contain 256 threads; the upper half takes part in barriers only.
__device__ float rms_sum_bf16(const ushort *x, uint width) {
    __shared__ float warp_sums[4];
    const uint tid = threadIdx.x;
    float sum = 0;
    if (tid < 128) {
        for (uint start = 4 * tid; start < width; start += 512)
            for (uint offset = 0; offset < 4; ++offset) {
                float value = h3_bf16_to_f32(x[start + offset]);
                sum = fmaf(value, value, sum);
            }
        for (uint distance = 16; distance; distance >>= 1)
            sum += __shfl_down_sync(0xffffffff, sum, distance);
        if (tid % 32 == 0) warp_sums[tid / 32] = sum;
    }
    __syncthreads();
    if (tid < 2) warp_sums[tid] += warp_sums[tid + 2];
    __syncthreads();
    if (tid == 0) warp_sums[0] += warp_sums[1];
    __syncthreads();
    return warp_sums[0];
}
"""]
helper = next((b for m, h, b in blocks(shader, r"inline float h3_erf_approx\(") ), None)
out += ["__device__ inline float h3_erf_approx(float value) " + translate(helper)]
for _, header, body in blocks(shader, r"(?:inline|static) int h3_reflect_coordinate\("):
    out.append("__device__ " + translate(header.replace("static ", "")) + translate(body))
launchers = []
for m, header, body in blocks(shader, r"kernel void (\w+)\("):
    name = m.group(1)
    if name not in selected:
        continue
    # Match the BF16 operation boundaries of the unfused PyTorch reference.
    # These intentional differences from Metal are numerical, not fast paths.
    if name in ("h3_rms_norm_bf16", "h3_adaln_bf16"):
        body = body.replace("float inverse = rsqrt(reductions[0] / float(args.width) + args.epsilon);",
                            "float sum = args.width % 4 == 0 ? rms_sum_bf16(x, args.width) : reductions[0];\n"
                            "    float inverse = rsqrt(sum / float(args.width) + args.epsilon);")
    if name == "h3_adaln_bf16":
        body = body.replace("normalized * (1.0f + scale) + shift",
                            "bf16_round(bf16_round(normalized) * bf16_round(1.0f + scale)) + shift")
    if name == "h3_gate_bf16":
        body = body.replace("h3_bf16_to_f32(branch[index]) * gate",
                            "bf16_round(h3_bf16_to_f32(branch[index]) * gate)")
    if name == "h3_swiglu_bf16":
        body = body.replace("gate / (1.0f + exp(-gate)) * up",
                            "bf16_round(gate / (1.0f + exp(-gate))) * up")
    if name == "h3_silu_mul_bf16":
        body = body.replace("value / (1.0f + exp(-value)) * other",
                            "bf16_round(value / (1.0f + exp(-value))) * other")
    if name == "h3_qkv_rope_bf16":
        begin = body.index("    float q_sum = 0.0f;")
        end = body.index("    float q_inverse", begin)
        body = body[:begin] + """    float q_sum = 0.0f, k_sum = 0.0f;
    if (args.head_dim == 128) {
        for (uint d = thread_position.x * 4; d < thread_position.x * 4 + 4; ++d) {
            float q = h3_bf16_to_f32(qkv[q_base + d]);
            float k = h3_bf16_to_f32(qkv[k_base + d]);
            q_sum = fma(q, q, q_sum); k_sum = fma(k, k, k_sum);
        }
        for (uint distance = 16; distance; distance >>= 1) {
            q_sum += __shfl_down_sync(0xffffffff, q_sum, distance);
            k_sum += __shfl_down_sync(0xffffffff, k_sum, distance);
        }
        q_sum = __shfl_sync(0xffffffff, q_sum, 0);
        k_sum = __shfl_sync(0xffffffff, k_sum, 0);
    } else {
        for (uint d = 0; d < args.head_dim; ++d) {
            float q = h3_bf16_to_f32(qkv[q_base + d]);
            float k = h3_bf16_to_f32(qkv[k_base + d]);
            q_sum = fma(q, q, q_sum); k_sum = fma(k, k, k_sum);
        }
    }
""".replace("thread_position.x", "threadIdx.x") + body[end:]
        body = body.replace("    if (dimension < args.rope_half) {",
                            "    q0 = bf16_round(q0); k0 = bf16_round(k0);\n    if (dimension < args.rope_half) {")
        for variable in ("q", "k"):
            for op in ("-", "+"):
                body = body.replace(f"{variable}0 * c {op} {variable}1 * s",
                    f"bf16_round({variable}0 * c) {op} bf16_round(bf16_round({variable}1) * s)")
    if name == "h3_head_rms_norm_bf16":
        body = body.replace("value * inverse * h3_bf16_to_f32(weight[d])",
                            "bf16_round(value * inverse) * h3_bf16_to_f32(weight[d])")
    if name == "h3_rope_text_bf16":
        body = body.replace("float c = rope_cos[row * half_dim + d];",
                            "float c = bf16_round(rope_cos[row * half_dim + d]);")
        body = body.replace("float s = rope_sin[row * half_dim + d];",
                            "float s = bf16_round(rope_sin[row * half_dim + d]);")
        body = body.replace("first * c - second * s", "bf16_round(first * c) - bf16_round(second * s)")
        body = body.replace("second * c + first * s", "bf16_round(second * c) + bf16_round(first * s)")
    args = []
    call = []
    builtin = []
    for arg in re.findall(r"([^,]+\[\[[^]]+\]\])", header.split("(", 1)[1]):
        decl, attr = arg.strip().split(" [[", 1)
        attr = attr.removesuffix("]]")
        var = re.search(r"(\w+)$", decl).group(1)
        if attr.startswith("buffer("):
            slot = int(re.search(r"\d+", attr).group())
            decl = translate(decl).replace("constant ", "").replace("&", "")
            args.append(decl)
            typ = decl[:decl.rfind(var)].strip()
            call.append(f"({typ})binding.p[{slot}]" if "*" in typ else f"binding.get<{typ}>({slot})")
        else:
            typ = decl.split()[0]
            dim = int(typ[-1]) if typ[-1].isdigit() else 1
            coords = {
                "thread_position_in_grid": [f"blockIdx.{a} * blockDim.{a} + threadIdx.{a}" for a in "xyz"],
                "threadgroup_position_in_grid": [f"blockIdx.{a}" for a in "xyz"],
                "thread_position_in_threadgroup": [f"threadIdx.{a}" for a in "xyz"],
                "threads_per_threadgroup": [f"blockDim.{a}" for a in "xyz"],
            }[attr]
            expr = coords[0] if dim == 1 else f"make_uint{dim}({', '.join(coords[:dim])})"
            builtin.append(f"    {decl} = {expr};")
    out.append(f"__global__ void {name}({', '.join(args)}) {{\n" + "\n".join(builtin) + translate(body[1:]))
    launchers.append(f'    if (!strcmp(name, "{name}")) {{ {name}<<<grid, block, 0, gpu->stream>>>({", ".join(call)}); return launch_ok(gpu); }}')
    if name == "h3_rms_norm_bf16":
        qwen_body = body.replace("normalized * h3_bf16_to_f32(weight[column])",
                                 "bf16_round(normalized) * h3_bf16_to_f32(weight[column])")
        qwen_body = qwen_body.replace("float sum = args.width % 4 == 0 ? rms_sum_bf16(x, args.width) : reductions[0];",
                                      "float sum = reductions[0];")
        qwen_name = "h3_qwen_rms_norm_bf16"
        out.append(f"__global__ void {qwen_name}({', '.join(args)}) {{\n" + "\n".join(builtin) + translate(qwen_body[1:]))
        launchers.append(f'    if (!strcmp(name, "{qwen_name}")) {{ {qwen_name}<<<grid, block, 0, gpu->stream>>>({", ".join(call)}); return launch_ok(gpu); }}')
(ROOT / "cuda/primitives.cuh").write_text("\n\n".join(out) + "\n")
(ROOT / "cuda/dispatch.inc").write_text("\n".join(launchers) + "\n")

wrappers = []
for m, header, body in blocks(host, r"int (h3_gpu_\w+)\("):
    name = m.group(1)
    if name.replace("h3_gpu_", "h3_", 1) not in selected:
        continue
    # Specialized host wrappers are handled by the native backend explicitly.
    if name in {"h3_gpu_adaln_bf16", "h3_gpu_qkv_rope_bf16", "h3_gpu_euler_bf16", "h3_gpu_head_rms_norm_bf16"}:
        continue
    if "h3_gpu_dispatch_" not in body or "@autoreleasepool" in body:
        continue
    s = header + body
    s = s.replace("H3GPU *gpu = GPU(opaque);", "h3_gpu *gpu = opaque;")
    s = re.sub(r"TENSOR\((\w+)\)\.(\w+)", r"\1->\2", s)
    s = s.replace('@"', '"').replace("NSUInteger", "size_t")
    s = s.replace("^(id<MTLComputeCommandEncoder> encoder)", "[&](Binding &encoder)")
    s = re.sub(r"\[encoder setBuffer:(\w+)->buffer offset:(.*?) atIndex:(\d+)\];",
               r"encoder.buffer(\3, \1, \2);", s, flags=re.S)
    s = re.sub(r"\[encoder setBytes:&(\w+) length:sizeof\((\w+)\) atIndex:(\d+)\];",
               r"encoder.arg(\3, &\1, sizeof(\2));", s)
    if re.search(r"\[encoder|@|\bid<", s):
        print("manual wrapper:", name)
        continue
    wrappers.append(s)
(ROOT / "cuda/primitive_wrappers.inc").write_text("// Generated from h3_gpu.m.\n" + "\n\n".join(wrappers) + "\n")
print("Generated", len(launchers), "kernels and", len(wrappers), "wrappers")
